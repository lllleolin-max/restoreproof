"""Byte-associate two exact ordinary wheels and replay the unchanged peer probe.

Run from any directory. Output must be a new ignored .local child in this repo.
No shared reviews are read or changed: peer-authored files are byte-identical
copies credited in docs/ITERATIONS.md and preserved by hash.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import zipfile

BEFORE = "b7ae9be639e2ac45f5c8c693ed76a267c1618169"
PROBE_SHA = "88162b9c958e87bafca682d2cfd65a19f57ae9bcb4664d5ceceba886d113c99e"
ORACLE_SHA = "062f86d216570ff9451776bf6d2b0d6368a796bdb602286bc0fd159911a181a6"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--after", required=True, help="exact substantive correction SHA")
    parser.add_argument("--final", help="optional exact subsequent UTF-8 correction SHA")
    parser.add_argument("--out", default=".local/boundary-replay")
    args = parser.parse_args()
    repository = Path(__file__).resolve().parents[1]
    out = (repository / args.out).resolve()
    assert out.is_relative_to(repository / ".local"), "logs must stay inside ignored local evidence"
    out.mkdir(parents=True, exist_ok=False)
    probe = repository / "tools/probes/round4.py"
    oracle = repository / "tools/peer_consumer_oracle.py"
    assert sha(probe) == PROBE_SHA and sha(oracle) == ORACLE_SHA
    records = []
    states = [("before", BEFORE, 1), ("after", args.after, 0)]
    if args.final:
        states.append(("final", args.final, 0))
    for label, commit, expected in states:
        commit = subprocess.check_output(["git", "rev-parse", commit], cwd=repository, text=True).strip()
        root = out / label
        root.mkdir()
        archive = root / "source.zip"
        subprocess.run(["git", "-c", "core.autocrlf=false", "archive", "--format=zip", "--output", str(archive), commit], cwd=repository, check=True)
        source = root / "source"
        source.mkdir()
        with zipfile.ZipFile(archive) as stream:
            stream.extractall(source)  # generated by our own named Git archive
        environment = root / "ordinary"
        subprocess.run([sys.executable, "-m", "venv", str(environment)], check=True)
        python = environment / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        def execute(name, command, expected=0):
            result = subprocess.run(list(map(str, command)), cwd=source, capture_output=True, text=True, encoding="utf-8", errors="replace")
            (root / (name + ".log")).write_text(result.stdout + result.stderr, encoding="utf-8")
            assert result.returncode == expected, (label, name, result.returncode, expected)
            return result
        execute("build", [python, "-m", "pip", "wheel", ".", "--no-deps", "--wheel-dir", root / "wheels"])
        wheel = next((root / "wheels").glob("*.whl"))
        execute("install", [python, "-m", "pip", "install", "--no-deps", wheel])
        inspector = "import hashlib,json,pathlib,sysconfig,restoreproof; p=pathlib.Path(restoreproof.__file__).resolve().parent; print(json.dumps({'ordinary':any(p.is_relative_to(pathlib.Path(sysconfig.get_path(n)).resolve()) for n in ('purelib','platlib')),'version':restoreproof.__version__,'modules':{n:hashlib.sha256((p/n).read_bytes()).hexdigest() for n in ('__init__.py','core.py','cli.py','fixture.py')}}))"
        association = json.loads(execute("association", [python, "-c", inspector]).stdout)
        assert association["ordinary"]
        for name, installed_hash in association["modules"].items():
            committed = subprocess.check_output(["git", "show", commit + ":src/restoreproof/" + name], cwd=repository)
            assert installed_hash == sha(source / "src/restoreproof" / name) == hashlib.sha256(committed).hexdigest()
        tests = execute("tests", [python, "-m", "unittest", "discover", "-s", "tests", "-v"])
        count = int(re.search(r"Ran (\d+) tests", tests.stdout + tests.stderr).group(1))
        execute("console", [python, "tools/verify_workflow.py"])
        contrast = json.loads(execute("contrast", [python, "tools/contrast.py"]).stdout)
        peer = json.loads(execute("consumer", [python, oracle]).stdout)
        scalar_result = execute("scalar", [python, probe], expected=expected)
        scalar = json.loads(scalar_result.stdout)
        assert scalar["passed"] == (expected == 0)
        assert peer["passed"] and peer["cases"] == 20
        if expected == 1:
            assert [case["sdk_escaped_exception"] for case in scalar["cases"]] == ["OverflowError", "ValueError"]
            assert [case["cli_exit"] for case in scalar["cases"]] == [1, 2]
        for number in (1, 2, 3):
            execute("historical_probe" + str(number), [python, repository / f"tools/probes/round{number}.py"])
        encoding_expected = 0 if label == "final" else 1
        encoding = execute("encoding", [python, repository / "tools/probes/round5.py"], expected=encoding_expected)
        if encoding_expected:
            assert "AssertionError: JSON byte autodetection accepted unsupported UTF-16 manifest" in encoding.stderr
        parent = subprocess.check_output(["git", "show", "-s", "--format=%P", commit], cwd=repository, text=True).strip()
        records.append({"state": label, "commit": commit, "parent": parent, "version": association["version"],
                        "archive_sha256": sha(archive), "wheel_sha256": sha(wheel),
                        "ordinary_install": association["ordinary"], "module_sha256": association["modules"],
                        "historical_suite_count": count, "suite_exit": tests.returncode, "actual_console_exit": 0,
                        "contrast": contrast, "peer_consumer_oracle": peer, "scalar_probe_exit": scalar_result.returncode,
                        "scalar_probe_sha256": sha(probe), "scalar_probe": scalar,
                        "old_probe_exits": [0, 0, 0], "encoding_probe_exit": encoding.returncode,
                        "encoding_probe_sha256": sha(repository / "tools/probes/round5.py")})
        print(json.dumps({"state": label, "commit": commit, "tests": count, "scalar_probe_exit": scalar_result.returncode, "peer_consumer_cases": peer["cases"]}), flush=True)
    assert records[1]["parent"] == BEFORE, "correction must directly follow rejected frozen state"
    if args.final:
        assert records[2]["parent"] == records[1]["commit"], "encoding correction must directly follow numeric correction"
    summary = {"environment": {"platform": sys.platform, "python": sys.version.split()[0]},
               "peer_probe_sha256": PROBE_SHA, "peer_oracle_sha256": ORACLE_SHA, "states": records}
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
